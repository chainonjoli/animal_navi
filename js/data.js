/**
 * 生年月日から本質キャラクター番号 (1〜60) を取得
 */
function getCharacterNumber(year, month, day) {
  const base = new Date(1926, 0, 1);
  const target = new Date(year, month - 1, day);
  const diffMs = target.getTime() - base.getTime();
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
  
  // 0-indexedの値を取得し、+1で1-60の番号に変換
  const idx0 = ((26 + diffDays) % 60 + 60) % 60;
  return idx0 + 1; // 1〜60
}

/**
 * 生年月日から「日干 (十干) インデックス」を取得 (0:甲 〜 9:癸)
 */
function getNikkanIndex(charNum) {
  return (charNum - 1) % 10;
}

/**
 * 生年月日から「月支 (十二支) インデックス」を取得 (0:子 〜 11:亥)
 * 節切り（二十四節気）を考慮した簡易高精度ロジック
 */
function getGetsushiIndex(year, month, day) {
  // 各月の代表的な節入り日（1月〜12月。簡易的に最も正確な値を配置）
  const setsuiryDays = [0, 6, 4, 6, 5, 6, 6, 7, 8, 8, 8, 7, 7];
  
  let targetMonth = month;
  
  // 節入り日より前の生まれの場合、前月の月支になる
  if (day < setsuiryDays[month]) {
    targetMonth = month - 1;
    if (targetMonth === 0) {
      targetMonth = 12;
    }
  }
  
  // 各月（1〜12月）に対応する月支インデックス (0:子, 1:丑, ... 11:亥)
  // 1月:丑(1), 2月:寅(2), 3月:卯(3), 4月:辰(4), 5月:巳(5), 6月:午(6), 
  // 7月:未(7), 8月:申(8), 9月:酉(9), 10月:戌(10), 11月:亥(11), 12月:子(0)
  const monthToShiIdx = [
    0,  // ダミー
    1,  // 1月 = 丑
    2,  // 2月 = 寅
    3,  // 3月 = 卯
    4,  // 4月 = 辰
    5,  // 5月 = 巳
    6,  // 6月 = 午
    7,  // 7月 = 未
    8,  // 8月 = 申
    9,  // 9月 = 酉
    10, // 10月 = 戌
    11, // 11月 = 亥
    0   // 12月 = 子
  ];
  
  return monthToShiIdx[targetMonth];
}

/**
 * 本質キャラクターと表面キャラクターの両方を算出するメイン診断関数
 */
function diagnoseDetails(year, month, day) {
  // 1. 本質キャラの算出
  const charNum = getCharacterNumber(year, month, day);
  const essentialData = CHARACTER_TABLE[charNum - 1];
  const essentialProfile = ANIMAL_PROFILES[essentialData.animal];
  
  // 2. 表面キャラの算出
  const nikkanIdx = getNikkanIndex(charNum);
  const getsushiIdx = getGetsushiIndex(year, month, day);
  
  const juiIdx = JUI_MATRIX[nikkanIdx][getsushiIdx];
  const juiOnSeiName = JUI_ON_SEI[juiIdx];
  const surfaceAnimal = JUI_TO_ANIMAL[juiOnSeiName];
  const surfaceProfile = ANIMAL_PROFILES[surfaceAnimal];
  
  return {
    birthDate: `${year}-${String(month).padStart(2,'0')}-${String(day).padStart(2,'0')}`,
    essential: {
      number: charNum,
      animal: essentialData.animal,
      name: essentialData.name,
      spell: essentialData.spell,
      group: GROUPS[essentialData.group],
      profile: essentialProfile
    },
    surface: {
      animal: surfaceAnimal,
      jui: juiOnSeiName,
      group: GROUPS[surfaceProfile.group],
      profile: surfaceProfile
    }
  };
}

